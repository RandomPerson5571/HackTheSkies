import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Reuse the image renderer shipped with Expo CLI; no native module is required.
const require = createRequire(import.meta.url);
const expoRequire = createRequire(require.resolve("expo/package.json"));
const cliRequire = createRequire(expoRequire.resolve("@expo/cli/package.json"));
const sharp = cliRequire("sharp");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(
  root,
  "src/features/profile/components/rewardSources.ts",
);
const sources = await readFile(sourcePath, "utf8");
const assets = new Map();
for (const [, relative] of sources.matchAll(/require\("([^"]+\.svg)"\)/g)) {
  if (assets.has(relative)) continue;
  const input = resolve(dirname(sourcePath), relative);
  const image = sharp(input, { density: 216 });
  const { data, info } = await image
    .png()
    .toBuffer({ resolveWithObject: true });
  assets.set(relative, {
    uri: `data:image/png;base64,${data.toString("base64")}`,
    width: info.width / 3,
    height: info.height / 3,
    scale: 3,
  });
}
const generated = sources
  .replace(/number(?=\s*[>\n])/g, 'import("react-native").ImageSourcePropType')
  .replace(
    /Record<RankId, number>/g,
    'Record<RankId, import("react-native").ImageSourcePropType>',
  )
  .replace(/require\("([^"]+\.svg)"\)/g, (_, relative) =>
    JSON.stringify(assets.get(relative)),
  );
await writeFile(
  sourcePath.replace(/\.ts$/, ".native.ts"),
  "// Generated by scripts/generate-native-art.mjs from the original SVGs.\n" +
    "// Inline PNGs avoid native SVG decoder differences and dev-server asset requests.\n" +
    generated,
);
console.log(`Generated ${assets.size} native reward images at 3x resolution.`);
