import { existsSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";

// Metro needs literal require paths so it can bundle photos on iOS, Android, and web.
export function mobileImageManifest(
  foods,
  catalogDirectory,
  manifestPath,
  allowedDirectory = catalogDirectory,
) {
  const entries = [];
  for (const food of foods) {
    if (!food.image?.localPath) continue;
    const absolute = resolve(catalogDirectory, food.image.localPath);
    if (!absolute.startsWith(`${resolve(allowedDirectory)}${sep}`))
      throw new Error(`Image must be inside the catalog directory: ${food.id}`);
    if (!existsSync(absolute))
      throw new Error(`Missing image file: ${food.id}`);
    let path = relative(dirname(manifestPath), absolute).split(sep).join("/");
    if (!path.startsWith(".")) path = `./${path}`;
    entries.push(
      `  ${JSON.stringify(food.id)}: require(${JSON.stringify(path)}),`,
    );
  }
  return `// Generated by the food catalog importer. Do not replace literal require paths.\nimport type { ImageSourcePropType } from "react-native";\n\nexport const catalogImages: Record<string, ImageSourcePropType> = {\n${entries.join("\n")}\n};\n`;
}
